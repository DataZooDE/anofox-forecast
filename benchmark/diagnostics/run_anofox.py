#!/usr/bin/env python3
"""Cross-check anofox-forecast ts_adf behavioral correctness against statsmodels reference.

This script validates the behavioral contract of the ts_adf DuckDB function:

  1. CLASSIFICATION: is_stationary matches the known direction of each fixture series
  2. STATISTIC SIGN: ADF t-statistic must be negative (unit root hypothesis regime)
  3. CRITICAL VALUES: cv_1pct, cv_5pct, cv_10pct within 10% of MacKinnon asymptotic constants
  4. NaN for short series: n < 4 → statistic = NaN, no exception raised

This is a behavioral contract test, NOT exact numeric parity.
statsmodels and anofox may select different lag counts via AIC, producing different
OLS regressions and statistics. Numeric comparison would therefore be misleading.

Usage:
    benchmark/.venv/bin/python benchmark/diagnostics/run_anofox.py
    # or from benchmark directory:
    cd benchmark && uv run python diagnostics/run_anofox.py

Requires:
    DuckDB CLI at DUCKDB_CLI_PATH (default: ./build/release/duckdb)
    reference_adf.json (generated by reference_values.py)

Env variables:
    ANOFOX_EXTENSION_PATH  -- path to the built .duckdb_extension file
                              (default: ./build/release/extension/anofox_forecast/anofox_forecast.duckdb_extension)
    DUCKDB_CLI_PATH        -- path to the DuckDB CLI binary
                              (default: ./build/release/duckdb)

Note on Python duckdb package:
    This script uses the DuckDB CLI via subprocess, not the Python duckdb package,
    to avoid version mismatch errors when the installed duckdb Python package
    version differs from the DuckDB version the extension was built against.
"""

import json
import math
import os
import re
import subprocess
import sys

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))

REFERENCE_PATH = os.path.join(SCRIPT_DIR, "reference_adf.json")

EXTENSION_PATH = os.environ.get(
    "ANOFOX_EXTENSION_PATH",
    os.path.join(
        REPO_ROOT,
        "build", "release", "extension", "anofox_forecast",
        "anofox_forecast.duckdb_extension",
    ),
)

DUCKDB_CLI = os.environ.get(
    "DUCKDB_CLI_PATH",
    os.path.join(REPO_ROOT, "build", "release", "duckdb"),
)

# MacKinnon (1994) asymptotic critical values (constant-only regression)
MACKINNON_ASYM = {
    "cv_1pct":  -3.43,
    "cv_5pct":  -2.86,
    "cv_10pct": -2.57,
}
CRIT_RTOL = 0.10  # 10% relative tolerance (covers sample-size variation n >= 30)


# ---------------------------------------------------------------------------
# DuckDB CLI helpers
# ---------------------------------------------------------------------------

def run_sql(sql):
    """Execute SQL via the DuckDB CLI, return JSON rows."""
    result = subprocess.run(
        [DUCKDB_CLI, "-json", "-c", sql],
        capture_output=True,
        text=True,
        timeout=30,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"DuckDB CLI failed (exit {result.returncode}):\n"
            f"stdout: {result.stdout}\nstderr: {result.stderr}"
        )
    stdout = result.stdout.strip()
    if not stdout or stdout == "[]":
        return []

    # DuckDB CLI outputs bare nan which is not valid JSON; replace with null
    stdout_fixed = re.sub(r':\s*nan\b', ': null', stdout)
    stdout_fixed = re.sub(r':\s*-?inf\b', ': null', stdout_fixed)

    try:
        return json.loads(stdout_fixed)
    except json.JSONDecodeError as e:
        raise RuntimeError(
            f"Could not parse DuckDB JSON output: {e}\nstdout: {stdout!r}"
        )


def run_ts_adf(series, max_lags=-1):
    """Run ts_adf on a Python list of float values via the DuckDB CLI.

    Returns dict with all STRUCT fields; None → float('nan').
    """
    vals = ", ".join(str(v) for v in series)
    sql = (
        f"LOAD '{EXTENSION_PATH}';\n"
        f"SELECT\n"
        f"    (r).statistic     AS statistic,\n"
        f"    (r).p_value       AS p_value,\n"
        f"    (r).lags          AS lags,\n"
        f"    (r).is_stationary AS is_stationary,\n"
        f"    (r).cv_1pct       AS cv_1pct,\n"
        f"    (r).cv_5pct       AS cv_5pct,\n"
        f"    (r).cv_10pct      AS cv_10pct\n"
        f"FROM (\n"
        f"    SELECT ts_adf(\n"
        f"        LIST_VALUE({vals}),\n"
        f"        {max_lags}::INTEGER\n"
        f"    ) AS r\n"
        f") t;\n"
    )

    rows = run_sql(sql)
    if not rows:
        raise RuntimeError("ts_adf returned no rows")

    row = rows[0]

    def maybe_nan(v):
        return float("nan") if v is None else float(v)

    return {
        "statistic":     maybe_nan(row.get("statistic")),
        "p_value":       maybe_nan(row.get("p_value")),
        "lags":          int(row.get("lags") or 0),
        "is_stationary": bool(row.get("is_stationary")),
        "cv_1pct":       maybe_nan(row.get("cv_1pct")),
        "cv_5pct":       maybe_nan(row.get("cv_5pct")),
        "cv_10pct":      maybe_nan(row.get("cv_10pct")),
    }


# ---------------------------------------------------------------------------
# Assertion helpers
# ---------------------------------------------------------------------------

def relative_error(actual, expected):
    denom = abs(expected)
    if denom < 1e-15:
        return abs(actual - expected)
    return abs(actual - expected) / denom


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    print("Behavioral contract cross-check: ts_adf vs statsmodels ADF")
    print(f"  DuckDB CLI: {DUCKDB_CLI}")
    print(f"  Extension:  {EXTENSION_PATH}")
    print(f"  Reference:  {REFERENCE_PATH}")
    print(f"  Checks:     classification | statistic sign | critical values | NaN for short")
    print()

    # Preflight checks
    for path, label, hint in [
        (DUCKDB_CLI,    "DuckDB CLI",  "cmake --build build/release"),
        (EXTENSION_PATH,"Extension",   "make rust && cmake --build build/release"),
        (REFERENCE_PATH,"Reference",   "benchmark/.venv/bin/python benchmark/diagnostics/reference_values.py"),
    ]:
        if not os.path.exists(path):
            print(f"ERROR: {label} not found: {path}\nHint: {hint}", file=sys.stderr)
            sys.exit(1)

    with open(REFERENCE_PATH) as f:
        ref = json.load(f)

    failures = []
    total_checks = 0

    for series_name, series_data in ref["series"].items():
        data = series_data["data"]
        expected_direction = series_data.get("expected_direction", "unknown")
        is_short = len(data) < 4

        print(f"  [{series_name}] n={len(data)}, expected={expected_direction}")

        if is_short:
            # ----------------------------------------------------------------
            # Check 4: NaN for short series (n < 4)
            # ----------------------------------------------------------------
            total_checks += 1
            try:
                result = run_ts_adf(data, max_lags=-1)
                if not math.isnan(result["statistic"]):
                    failures.append(
                        f"[{series_name}] short series: "
                        f"expected NaN statistic, got {result['statistic']}"
                    )
                    print(f"    NaN check: FAIL (got {result['statistic']})")
                else:
                    print(f"    NaN for n < 4: OK")
            except Exception as exc:
                failures.append(f"[{series_name}] short series exception: {exc}")
            continue

        try:
            result = run_ts_adf(data, max_lags=-1)
        except Exception as exc:
            failures.append(f"[{series_name}] ts_adf raised exception: {exc}")
            continue

        print(
            f"    stat={result['statistic']:.4f}, p={result['p_value']:.4f}, "
            f"lags={result['lags']}, is_stationary={result['is_stationary']}"
        )

        # ----------------------------------------------------------------
        # Check 1: Classification (is_stationary matches expected direction)
        # ----------------------------------------------------------------
        total_checks += 1
        if expected_direction == "stationary":
            ok = result["is_stationary"] is True
        elif expected_direction == "nonstationary":
            ok = result["is_stationary"] is False
        else:
            ok = True  # unknown — skip
        print(f"    classification: {'OK' if ok else 'FAIL'} "
              f"(expected is_stationary={'True' if expected_direction == 'stationary' else 'False'}, "
              f"got {result['is_stationary']})")
        if not ok:
            failures.append(
                f"[{series_name}] classification: "
                f"expected is_stationary={expected_direction=='stationary'}, "
                f"got {result['is_stationary']}"
            )

        # ----------------------------------------------------------------
        # Check 2: Statistic sign (ADF t-stat must be negative)
        # ----------------------------------------------------------------
        total_checks += 1
        stat = result["statistic"]
        if not math.isnan(stat):
            ok_sign = stat < 0
            print(f"    statistic sign: {'OK' if ok_sign else 'FAIL'} ({stat:.4f} {'< 0' if ok_sign else '>= 0'})")
            if not ok_sign:
                failures.append(
                    f"[{series_name}] statistic sign: {stat:.4f} is not negative"
                )
        else:
            failures.append(f"[{series_name}] statistic: got NaN for non-short series")

        # ----------------------------------------------------------------
        # Check 3: Critical values within CRIT_RTOL of MacKinnon asymptotic
        # ----------------------------------------------------------------
        for field, asym_val in MACKINNON_ASYM.items():
            total_checks += 1
            actual_cv = result[field]
            if math.isnan(actual_cv):
                failures.append(f"[{series_name}] {field}: got NaN, expected ~{asym_val}")
                print(f"    {field}: FAIL (NaN)")
                continue
            err = relative_error(actual_cv, asym_val)
            ok_cv = err <= CRIT_RTOL
            print(
                f"    {field}: actual={actual_cv:.4f} asym={asym_val:.4f} "
                f"rerr={err:.3f} {'OK' if ok_cv else 'FAIL'}"
            )
            if not ok_cv:
                failures.append(
                    f"[{series_name}] {field}: actual={actual_cv:.4f}, "
                    f"asym={asym_val:.4f}, rerr={err:.4f} > {CRIT_RTOL}"
                )

    print()
    print(f"Total checks: {total_checks} | Failures: {len(failures)}")
    if failures:
        print(f"\nFAILED ({len(failures)}):")
        for fail in failures:
            print(f"  - {fail}")
        sys.exit(1)
    else:
        print("\nAll behavioral contract checks PASSED")
        print("  - Classification matches expected stationarity direction")
        print("  - ADF statistics are negative")
        print("  - Critical values match MacKinnon asymptotic within 10%")
        print("  - Short series returns NaN without exception")
        sys.exit(0)


if __name__ == "__main__":
    main()
